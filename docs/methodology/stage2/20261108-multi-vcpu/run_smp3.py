#!/usr/bin/env python3
"""SMP3 of README.md: restart of vCPU 1 after CPU_OFF, with the CPU
hotplug init (hotplug-init.c) instead of the KDAL CI init.

Usage: [ONLY=H1,H2,H3] run_smp3.py HAVEN_REPO KDAL_SRC IMAGE KDAL_KO OUT

Runs: H1 free boot to power-off; H2 read-back v12 (grant-smp-v12.json)
at HOTPLUG-OFF; H3 the same at KDAL-DEMAND-END. HAVEN is built from the
repository's HEAD with qemu-psci and HAVEN_PART_A_VCPUS=2.
"""
import importlib.util
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("smp1", os.path.join(HERE, "run_smp1.py"))
smp1 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(smp1)
rc = smp1.rc
GRANT = os.path.join(HERE, "grant-smp-v12.json")
ONLY = os.environ.get("ONLY", "").split(",") if os.environ.get("ONLY") else None


def main():
    repo, ksrc, image, ko, out = (os.path.abspath(x) for x in sys.argv[1:6])
    os.makedirs(out, exist_ok=True)
    work = tempfile.mkdtemp(prefix="smp3-")
    init, cpio = os.path.join(work, "init"), os.path.join(work, "initramfs.cpio")
    subprocess.run(["clang", "--target=aarch64-linux-gnu", "-ffreestanding", "-nostdlib", "-static", "-O2",
                    "-fno-stack-protector", "-fuse-ld=lld", "-Wl,-e,_start", "-o", init,
                    os.path.join(HERE, "hotplug-init.c")], check=True)
    subprocess.run([sys.executable, os.path.join(ksrc, "scripts/ci/mkcpio.py"), cpio, init, ko], check=True)
    ipa = 0x48000000
    dts, dtb = os.path.join(work, "smp.dts"), os.path.join(work, "smp.dtb")
    with open(dts, "w") as fh:
        fh.write(smp1.smp_dts(rc.dts(rc.CASES["B0"][2], ipa, ipa + os.path.getsize(cpio))))
    subprocess.run(["dtc", "-q", "-I", "dts", "-O", "dtb", "-o", dtb, dts], check=True)
    b = smp1.build(repo, os.path.join(work, "build"), os.path.join(out, "build.log"))
    lines = []
    pat = (r"HOTPLUG|CPU1: Booted|CPU1: shutdown|CPU1 killed|smp: Brought up|psci:|CPU_OFF|CPU_ON|"
           r"switched off|CPU 1 ready|not off|parked|KDAL-DEMAND-END|delivered|not delivered|EL2 FATAL")
    if not ONLY or "H1" in ONLY:
        d = os.path.join(out, "H1")
        shutil.rmtree(d, ignore_errors=True)
        os.makedirs(d)
        secs = smp1.free_boot(b, image, dtb, cpio, ipa + rc.PA_OFFSET, os.path.join(d, "uart.log"))
        t = open(os.path.join(d, "uart.log"), errors="replace").read()
        lines += [f"## H1 free boot ({secs} s)", ""] + [f"- `{x}`" for x in smp1.pick(t, pat, 30)] + [""]
    for name, marker in (("H2", "HOTPLUG-OFF"), ("H3", "KDAL-DEMAND-END")):
        if ONLY and name not in ONLY:
            continue
        d = os.path.join(out, name)
        shutil.rmtree(d, ignore_errors=True)
        os.makedirs(d)
        cmd = [sys.executable, os.path.join(repo, "tools/readback/readback.py"), b, GRANT,
               os.path.join(d, "rb"), "--cpu", "cortex-a72", "--wait", "90", "--device", rc.DEV,
               "--guest-a", image, "--load", f"{dtb}@{rc.DTB_PA:#x}", "--load", f"{cpio}@{ipa + rc.PA_OFFSET:#x}",
               "--marker", marker]
        r = subprocess.run(cmd, capture_output=True, text=True)
        text = (r.stdout + r.stderr).replace(work, "<tmp>").replace(repo, "<workspace>/haven")
        with open(os.path.join(d, "readback.txt"), "w") as fh:
            fh.write(text)
        for f in ("readback.json", "uart.log"):
            if os.path.exists(os.path.join(d, "rb", f)):
                shutil.copy(os.path.join(d, "rb", f), os.path.join(d, f))
        shutil.rmtree(os.path.join(d, "rb"))
        lines += [f"## {name} read-back v12 at {marker}", ""]
        lines += [f"- `{x}`" for x in smp1.pick(text, r"RESULT|FINDING|CPU [0-9]: granted|waiting|time limit", 14)]
        lines.append("")
    with open(os.path.join(out, "results.md"), "w") as fh:
        fh.write("# SMP3 runs (generated by run_smp3.py)\n\n" + "\n".join(lines))
    print("\n".join(lines))
    shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    main()
